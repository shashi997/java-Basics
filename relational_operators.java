public class relational_operators {
    public static void main(String[] args) {
        
        int x = 6;
        int y = 8;
        int z = 6;

        boolean result = x > y;
        boolean result1 = x <= z;

        System.out.println(result);
        System.out.println(result1);

        double a = 5.6;
        double b = 7.8;

        boolean result2 = a >= b;

        System.out.println(result2);
    }
}
